const DICTS: Record<Lang, Dict> = { en, ta, si };

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "en",
  setLang: () => {},
  t: en,
});

function initialLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const s = window.localStorage.getItem(LANG_KEY);
    if (s === "ta" || s === "si") return s;
  } catch {
    /* ignore */
  }
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      window.localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* private mode — language just won't persist */
    }
  }, [lang ]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);

  return <LangCtx.Provider value={{ lang, setLang, t: DICTS[lang] }}>{children}</LangCtx.Provider>;
}

export function useI18n() {
  return useContext(LangCtx);
}

/** Cycle EN → த → සි → EN (used by the compact header toggle). */
export function nextLang(lang: Lang): Lang {
  return lang === "en" ? "ta" : lang === "ta" ? "si" : "en";
}
